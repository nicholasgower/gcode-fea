"""Abaqus/CalculiX input writing."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from ..voxel import VoxelMesh

Array = np.ndarray


def write_abaqus(
    mesh: VoxelMesh,
    path: str | Path,
    material: dict,
    node_sets: dict[str, Array] | None = None,
    displacement: float = 0.5,
    element_sets: bool = True,
    title: str = "GCode-FEA coupon",
) -> Path:
    lines = _mesh_block(mesh, material, title, element_sets)
    lines.extend(_node_set_blocks(node_sets or {}))
    lines.extend(_step_block("abaqus", node_sets or {}, displacement))
    return _write(path, lines)


def write_calculix(
    mesh: VoxelMesh,
    path: str | Path,
    material: dict,
    node_sets: dict[str, Array] | None = None,
    displacement: float = 0.5,
    element_sets: bool = True,
    title: str = "GCode-FEA coupon",
) -> Path:
    lines = _mesh_block(mesh, material, title, element_sets)
    lines.extend(_node_set_blocks(node_sets or {}))
    lines.extend(_step_block("calculix", node_sets or {}, displacement))
    return _write(path, lines)


def _mesh_block(
    mesh: VoxelMesh,
    material: dict,
    title: str,
    element_sets: bool,
) -> list[str]:
    if mesh.n_elements == 0:
        raise ValueError("cannot write an empty mesh")
    lines = [
        "*HEADING",
        title,
        "** generated by gcode-fea; units: mm, MPa, N, tonne",
        "** element type C3D8/HEX8, 8-node linear brick",
        "*NODE, NSET=NALL",
    ]
    for index, (x, y, z) in enumerate(mesh.nodes, start=1):
        lines.append(f"{index}, {x:.9g}, {y:.9g}, {z:.9g}")
    lines.append("*ELEMENT, TYPE=C3D8, ELSET=EALL")
    for index, element in enumerate(mesh.elements, start=1):
        nodes = ", ".join(str(int(node) + 1) for node in element)
        lines.append(f"{index}, {nodes}")

    if element_sets:
        for name, indices in mesh.element_sets().items():
            if name == "EALL" or indices.size == 0:
                continue
            lines.extend(_chunked_set("ELSET", name, indices + 1))

    name = material.get("name", "PLA").upper().replace(" ", "_")
    lines.extend(
        [
            f"*SOLID SECTION, ELSET=EALL, MATERIAL={name}",
            f"*MATERIAL, NAME={name}",
            "*ELASTIC",
            (
                f"{material['youngs_modulus_mpa']:.6f}, "
                f"{material['poisson_ratio']:.6f}"
            ),
            "*DENSITY",
            f"{material['density_g_cm3'] * 1e-9:.9g}",
        ]
    )
    return lines


def _step_block(
    solver: str,
    node_sets: dict[str, Array],
    displacement: float,
) -> list[str]:
    lines = [
        "*STEP, NAME=LOAD, NLGEOM=NO",
        "*STATIC",
        "0.05, 1.0",
        "*BOUNDARY",
    ]
    fixed = (
        ("LEFT_CENTER", 1),
        ("RIGHT_CENTER", 1),
        ("LEFT_CORNERS", 2),
        ("RIGHT_CORNERS", 2),
        ("RIGHT_EDGE", 3),
    )
    for name, dof in fixed:
        if name in node_sets and len(node_sets[name]) > 0:
            lines.append(f"{name}, {dof}, {dof}, 0.0")
    if "LEFT_EDGE" in node_sets and len(node_sets["LEFT_EDGE"]) > 0:
        lines.extend(
            [
                "*BOUNDARY",
                f"LEFT_EDGE, 1, 1, {displacement:.6f}",
            ]
        )
    if solver == "abaqus":
        lines.extend(
            [
                "*OUTPUT, FIELD, FREQUENCY=1",
                "*ELEMENT OUTPUT",
                "S, E",
                "*NODE OUTPUT",
                "U, RF",
            ]
        )
    else:
        lines.extend(
            [
                "*NODE FILE",
                "U, RF",
                "*EL FILE",
                "S, E",
            ]
        )
    lines.append("*END STEP")
    return lines


def _node_set_blocks(node_sets: dict[str, Array]) -> list[str]:
    lines: list[str] = []
    for name, indices in node_sets.items():
        if len(indices) == 0:
            continue
        lines.extend(_chunked_set("NSET", name, indices))
    return lines


def _chunked_set(kind: str, name: str, indices: Array, per_line: int = 16) -> list[str]:
    if not name.replace("_", "").isalnum():
        raise ValueError(f"invalid set name: {name}")
    values = [str(int(value)) for value in indices]
    lines = [f"*{kind}, {kind}={name}"]
    for start in range(0, len(values), per_line):
        lines.append(", ".join(values[start : start + per_line]))
    return lines


def _write(path: str | Path, lines: list[str]) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n")
    return target
